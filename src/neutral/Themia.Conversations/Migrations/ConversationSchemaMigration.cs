    private void CreateConstraints(bool sqlServer, bool filteredUnique)
    {
        // conversations: one per subject, and the (tenant_id, id) key every child binds.
        Create.UniqueConstraint("ux_conversations_subject").OnTable(ConversationsTable).Columns("tenant_id", "subject_type", "subject_id");
        Create.UniqueConstraint("ux_conversations_tenant_id").OnTable(ConversationsTable).Columns("tenant_id", "id");

        // participants: the (tenant_id, conversation_id, id) key that messages, attachments and guest sessions bind; one participant per person per
        // conversation; lookup indexes to find the same person across conversations (a data-subject request).
        Create.UniqueConstraint("ux_conversation_participants_key").OnTable(ParticipantsTable).Columns("tenant_id", "conversation_id", "id");
        if (filteredUnique)
        {
            // PostgreSQL and SQL Server treat NULLs as equal in a unique index on SQL Server and as distinct on PostgreSQL; a filter makes both exact.
            Execute.Sql($"CREATE UNIQUE INDEX ux_conversation_participants_user_ref ON {ParticipantsTable} (tenant_id, conversation_id, user_ref) WHERE user_ref IS NOT NULL;");
            Execute.Sql($"CREATE UNIQUE INDEX ux_conversation_participants_contact ON {ParticipantsTable} (tenant_id, conversation_id, contact_hash) WHERE contact_hash IS NOT NULL;");
        }
        else
        {
            // MySQL allows repeated NULLs in a unique index natively.
            Create.UniqueConstraint("ux_conversation_participants_user_ref").OnTable(ParticipantsTable).Columns("tenant_id", "conversation_id", "user_ref");
            Create.UniqueConstraint("ux_conversation_participants_contact").OnTable(ParticipantsTable).Columns("tenant_id", "conversation_id", "contact_hash");
        }

        Create.Index("ix_conversation_participants_contact_lookup").OnTable(ParticipantsTable).OnColumn("tenant_id").Ascending().OnColumn("contact_hash").Ascending();
        Create.Index("ix_conversation_participants_user_ref_lookup").OnTable(ParticipantsTable).OnColumn("tenant_id").Ascending().OnColumn("user_ref").Ascending();
        Create.ForeignKey("fk_conversation_participants_conversation").FromTable(ParticipantsTable).ForeignColumns("tenant_id", "conversation_id")
            .ToTable(ConversationsTable).PrimaryColumns("tenant_id", "id");

        // messages: NONCLUSTERED primary key and clustering on (conversation_id, seq) on SQL Server; the idempotency key doubles as the index of the participant key.
        if (sqlServer)
        {
            Execute.Sql($"ALTER TABLE {MessagesTable} ADD CONSTRAINT pk_conversation_messages PRIMARY KEY NONCLUSTERED (id);");
            Execute.Sql($"ALTER TABLE {MessagesTable} ADD CONSTRAINT ux_conversation_messages_seq UNIQUE CLUSTERED (conversation_id, seq);");
        }
        else
        {
            Create.PrimaryKey("pk_conversation_messages").OnTable(MessagesTable).Column("id");
            Create.UniqueConstraint("ux_conversation_messages_seq").OnTable(MessagesTable).Columns("conversation_id", "seq");
        }

        Create.UniqueConstraint("ux_conversation_messages_key").OnTable(MessagesTable).Columns("tenant_id", "conversation_id", "id");
        Create.UniqueConstraint("ux_conversation_messages_idempotency").OnTable(MessagesTable)
            .Columns("tenant_id", "conversation_id", "participant_id", "client_message_id");
        Create.ForeignKey("fk_conversation_messages_participant").FromTable(MessagesTable).ForeignColumns("tenant_id", "conversation_id", "participant_id")
            .ToTable(ParticipantsTable).PrimaryColumns("tenant_id", "conversation_id", "id");
        Create.ForeignKey("fk_conversation_messages_conversation").FromTable(MessagesTable).ForeignColumns("tenant_id", "conversation_id")
