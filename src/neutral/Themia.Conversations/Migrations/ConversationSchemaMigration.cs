        [
            (ConversationsTable, "tenant_id", TenantIdWidth, false),
            (ConversationsTable, "subject_type", SubjectTypeWidth, false),
            (ConversationsTable, "subject_id", SubjectIdWidth, false),
            (ParticipantsTable, "tenant_id", TenantIdWidth, false),
            (ParticipantsTable, "user_ref", UserRefWidth, true),
            (ParticipantsTable, "pepper_key_id", 40, true),
            (MessagesTable, "tenant_id", TenantIdWidth, false),
            (MessagesTable, "client_message_id", 64, false),
            (AttachmentsTable, "tenant_id", TenantIdWidth, false),
            (AttachmentsTable, "storage_key", 300, false),
            (GuestSessionsTable, "tenant_id", TenantIdWidth, false),
            (EventsTable, "tenant_id", TenantIdWidth, false),
            (TombstonesTable, "tenant_id", TenantIdWidth, false),
            (TombstonesTable, "subject_type", SubjectTypeWidth, false),
            (TombstonesTable, "subject_id", SubjectIdWidth, false),
        ];

        foreach (var (table, column, width, nullable) in columns)
        {
            // COLLATE belongs to the type spec and must precede NULL/NOT NULL on both engines.
            Execute.Sql($"ALTER TABLE {table} {alterVerb} {quote(column)} {text(width)} COLLATE {collation} " + (nullable ? "NULL;" : "NOT NULL;"));
        }
    }
