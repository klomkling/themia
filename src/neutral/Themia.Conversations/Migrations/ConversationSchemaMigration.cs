/// <summary>
/// Creates the whole conversation schema on PostgreSQL, MySQL and SQL Server: <c>conversations</c>, <c>conversation_participants</c>,
/// <c>conversation_messages</c>, <c>conversation_attachments</c>, <c>conversation_guest_sessions</c>, <c>conversation_events</c> and
/// <c>conversation_tombstones</c>. Every table the design needs is here, including those whose logic ships later: a migration that has
/// shipped is never edited, so what is expensive to change afterwards (keys, clustering, column types, NOT NULL columns, unique constraints,
/// foreign-key shape) has to be right the first time.
/// </summary>
/// <remarks>
/// <para><b>Literal table names on every engine, never <c>InSchema(...)</c></b>; see <c>ChallengeSchemaMigration</c>.</para>
/// <para><b>Tenant isolation is in the keys.</b> Every table carries <c>tenant_id</c>. Each child binds its parent on <c>(tenant_id, conversation_id, ...)</c>,
/// so a row can point neither at another tenant's parent nor at another conversation's participant or message of the same tenant. Each parent exposes
/// the matching unique key, in the same column order, which is what a MySQL foreign key needs; every child key column set has an index whose leading
/// columns match, because PostgreSQL and SQL Server create none for a foreign key. The actions are <c>NO ACTION</c>: a purge deletes children first,
/// in code, after locking the conversation row.</para>
/// <para><b>Byte-exact collation on every compared string column</b> (MySQL <c>utf8mb4_bin</c>, SQL Server <c>Latin1_General_BIN2</c>), pinned after the
/// tables exist and before any key or index, because SQL Server cannot alter the collation of an indexed column and MySQL refuses a foreign key
/// between columns of different collation. Without it <c>Acme</c> and <c>acme</c> are the same tenant, the keys above isolate nothing, and
/// <c>client_message_id</c> <c>abc</c> would answer <c>ABC</c> with a false duplicate. PostgreSQL's comparison is already byte-exact.</para>
/// <para><b>Ids are GUIDs</b> (<c>uuid</c> / <c>CHAR(36)</c> / <c>uniqueidentifier</c>), generated by the app with <c>Guid.NewGuid()</c> (the neutral packages target
/// net8, which has no version 7). On SQL Server <c>conversation_messages</c> has a NONCLUSTERED primary key and is clustered on <c>(conversation_id, seq)</c>,
/// the order every list reads in: a random GUID as clustering key would fragment the table.</para>
/// <para><b>No <c>updated_at</c> on <c>conversations</c></b>, following <c>ContentSchemaMigration</c>; the state changes that matter have their own columns.</para>
/// </remarks>
